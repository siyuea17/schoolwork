// ============================================================================
// 文件：main.cpp
// 角色：程序的"入口点"——整个应用程序从这里开始执行
//
// 每个 C++ 程序都必须有一个 main() 函数，操作系统从这里开始运行你的程序。
// 这个 main() 函数非常简短，因为真正的工作都交给了各个类去做了。
// 这是一个好的设计模式：main() 只做"启动"相关的事。
//
// Qt 应用程序的启动流程（三件套）：
//   ┌─────────────────────────────────────────────────────┐
//   │  QApplication app(argc, argv);                      │
//   │    ↓  创建"应用程序对象"。                           │
//   │    ↓  它管理整个程序的生命周期，处理事件循环。        │
//   │    ↓  每个 Qt GUI 程序有且只有一个 QApplication。    │
//   ├─────────────────────────────────────────────────────┤
//   │  MainWindow window;                                 │
//   │    ↓  创建主窗口对象。                               │
//   │    ↓  在构造函数中，它会创建 GameWidget、状态栏等。   │
//   ├─────────────────────────────────────────────────────┤
//   │  window.show();                                     │
//   │    ↓  让窗口显示在屏幕上。                           │
//   ├─────────────────────────────────────────────────────┤
//   │  return app.exec();                                 │
//   │    ↓  进入"事件循环"（Event Loop）。                 │
//   │    ↓  程序开始等待并响应用户操作。                    │
//   │    ↓  只有窗口关闭时，exec() 才返回。                │
//   └─────────────────────────────────────────────────────┘
//
// 什么是"事件循环"？
//   想象一个餐厅服务员：他站在大堂里，不断等待顾客的需求，
//   有需求就处理，处理完继续等待。事件循环就是这样：
//     while (窗口还在运行) {
//         等待下一个事件（鼠标点击、键盘、定时器...）
//         把事件分发（dispatch）给对应的处理函数
//     }
//   app.exec() 内部就包含了这个 while 循环。
// ============================================================================

#include "MainWindow.h"                // 主窗口类
#include <QtWidgets/QApplication>       // Qt 应用程序类

// ============================================================================
// main() 函数 —— 程序的起点
//
// 参数说明（这是 C 语言的遗产，Qt 基本用不到，但要传给它）：
//   argc = argument count，命令行参数的个数
//   argv = argument values，命令行参数的内容（字符串数组）
//
// 返回值：
//   0  = 程序正常退出
//   非0 = 发生错误（这里始终返回 app.exec() 的结果）
//
// 细心的你可能注意到了：MainWindow 对象是在栈上创建的（不是 new），
// 但它里面的 GameWidget、QLabel 等都是 new 出来的指针。
// 它们怎么被释放？
//   答案：Qt 的父子对象树机制。
//   MainWindow 销毁时，会自动递归删除所有子对象。
//   所以不需要手动 delete 那些 new 出来的东西。
// ============================================================================
int main(int argc, char *argv[])
{
    // ---- 第1步：创建应用程序对象 ----
    // QApplication 负责：
    //   - 初始化 Qt 框架
    //   - 管理程序级别的事件（如程序退出）
    //   - 处理命令行参数（如 -style fusion 改变程序风格）
    //   - 管理剪贴板、桌面信息等全局资源
    QApplication app(argc, argv);

    // ---- 第2步：创建并显示主窗口 ----
    MainWindow window;     // 在栈上创建（离开 main 作用域时自动销毁）
    window.show();         // 显示窗口！
                           // 这时 MainWindow 的构造函数已经执行完毕，
                           // 棋盘已生成、信号槽已连接、计时器已开始。

    // ---- 第3步：进入事件循环 ----
    // app.exec() 会一直在内部循环，直到所有窗口关闭。
    // 在这期间：
    //   - 你的鼠标点击 → Qt 捕获 → 构造 QMouseEvent → 调用 mousePressEvent()
    //   - 定时器到期 → Qt 捕获 → 发出 timeout() 信号 → 调用连接的槽函数
    //   - 需要重绘 → Qt 捕获 → 构造 QPaintEvent → 调用 paintEvent()
    //
    // exec() 的返回值会成为 main() 的返回值，
    // 通常 0 = 正常退出。
    return app.exec();
}
