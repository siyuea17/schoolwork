// ============================================================================
// 文件：main.cpp
// 角色：程序的"入口点"——操作系统从这里开始执行
//
// 每一个 C++ 程序都必须有一个 main() 函数。
// 这个 main() 非常简短，因为它只做"启动"相关的事，
// 真正的工作都交给了各个类去做了。
// 这是一个好的设计模式：main() 只负责启动，不掺和业务逻辑。
//
// Qt 应用程序的生命周期（三件套）：
//   ┌─────────────────────────────────────────────────────┐
//   │  QApplication app(argc, argv);                      │
//   │    ↓  创建"应用程序对象"。                           │
//   │    ↓  它管理整个程序，处理"事件循环"。               │
//   │    ↓  每个 Qt GUI 程序有且只有一个 QApplication。    │
//   ├─────────────────────────────────────────────────────┤
//   │  MainWindow window;                                 │
//   │    ↓  创建主窗口对象。                               │
//   │    ↓  构造函数里会创建 StartWidget、状态栏等。       │
//   ├─────────────────────────────────────────────────────┤
//   │  window.show();                                     │
//   │    ↓  让窗口显示在屏幕上。                           │
//   ├─────────────────────────────────────────────────────┤
//   │  return app.exec();                                 │
//   │    ↓  进入"事件循环"。                               │
//   │    ↓  程序开始等待并响应用户操作。                    │
//   │    ↓  只有窗口关闭时，exec() 才返回。                │
//   └─────────────────────────────────────────────────────┘
//
// 什么是"事件循环"（Event Loop）？
//   想象一个餐厅服务员：他站在大堂里，不断等待顾客的需求，
//   有需求就处理，处理完继续等待。
//   事件循环就是这个"等待 → 处理 → 再等待"的循环：
//     while (窗口还在运行) {
//         等待下一个事件（鼠标点击、键盘输入、定时器通知...）
//         把事件分发（dispatch）给对应的处理函数
//     }
//   app.exec() 内部就包含了这个 while 循环。
//
// 关于 Qt 的父子对象树（Parent-Child Tree）：
//   MainWindow window 在栈上创建（不是用 new）。
//   但它里面的 GameWidget、QLabel 等都是用 new 创建的指针。
//   它们怎么被释放？
//     全部依赖 Qt 的父子对象树机制——
//     window 销毁时，会自动递归删除所有"以它为 parent"的子对象。
//     所以不需要手动写 delete。
// ============================================================================

#include "MainWindow.h"                // 自己写的主窗口类
#include <QtWidgets/QApplication>       // Qt 的应用程序类（管理程序生命周期）

// ============================================================================
// main() 函数 —— 程序的起点
//
// 参数说明（C 语言遗留下来的，Qt 一般用不到，但要传给 QApplication）：
//   argc = argument count，命令行参数的个数
//   argv = argument values，命令行参数的内容（字符串数组）
//
// 返回值：
//   0  = 程序正常退出
//   非0 = 发生错误
// ============================================================================
int main(int argc, char *argv[])
{
    // ---- 第1步：创建应用程序对象 ----
    // QApplication 这个对象负责：
    //   初始化 Qt 框架（注册事件系统、样式系统等）
    //   管理程序级别的事件（如最后的程序退出）
    //   保存全局资源（剪贴板、桌面信息等）
    QApplication app(argc, argv);

    // ---- 第2步：创建主窗口对象 ----
    // window 在栈上创建，离开 main 作用域时自动销毁
    // 在它的构造函数中：
    //   加载 MainWindow.ui → 创建工具栏/状态栏
    //   加载用户设置 → 初始化音频 → 创建 QStackedWidget
    //   创建 StartWidget（开始界面）→ 连接信号槽
    MainWindow window;

    // ---- 第3步：显示窗口 ----
    // 到这里，构造函数已经执行完毕：
    //   开始界面已显示（"连连看"大标题 + 三个按钮）
    //   背景音乐开始播放
    //   状态栏标签已创建但隐藏
    window.show();

    // ---- 第4步：进入事件循环 ----
    // app.exec() 会一直在内部循环，直到所有窗口关闭
    // 在这期间，Qt 自动处理：
    //   - 鼠标点击 → 识别点击事件 → 调用 mousePressEvent()
    //   - 定时器到期 → 发出 timeout() 信号 → 调用连接的槽函数
    //   - 画面需要刷新 → 发出 paint 事件 → 调用 paintEvent()
    //
    // exec() 的返回值会成为 main() 的返回值
    // 通常 0 = 正常退出
    return app.exec();
}
